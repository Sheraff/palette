/**
 * Track P probe: build the instrumented mirror of the v2-3 runtime.
 *
 * PROBES ONLY — `research/v2-3/` is never written. This copies the runtime into
 * `research/v2-3-experiments/track-p/.variant/` and rewrites it so that:
 *
 *   - every tunable numeric literal `T` at registry site `i` becomes `__P.v(i, T)`, which counts the
 *     evaluation and, when site `i` is the perturbation target, returns `T * factor`;
 *   - every comparison whose operand is such a literal is wrapped in `__P.cmp(i, left, right, op,
 *     side)`, which records how close the compared value came to the threshold.
 *
 * One tree therefore serves both roles: a census run (no target) yields firing counts and, for every
 * site, how many evaluations would have flipped their boolean under +-10/20/50 %; a perturbation run
 * sets `TRACK_P_SITE` / `TRACK_P_FACTOR` and re-extracts. This matters because 912 sites x 2 signs x
 * a real corpus is tens of core-hours, and the census proves most sites cannot flip any decision at
 * all — those need no run.
 *
 * The transform goes through the TypeScript AST and printer rather than text splicing, because
 * comparison wraps and literal wraps nest (`total * 0.08 < 0.3`) and overlapping text edits silently
 * corrupt them. `verify-instrumentation.ts` checks the mirror reproduces baseline winners exactly.
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { fileURLToPath } from "node:url"
import ts from "typescript"
import type { RegistryEntry } from "./build-registry.ts"

const trackRoot = resolve(fileURLToPath(new URL("..", import.meta.url)))
const repoRoot = resolve(trackRoot, "../../..")
const runtimeDir = resolve(repoRoot, "research/v2-3")
const variantDir = resolve(trackRoot, ".variant")

const registry = JSON.parse(readFileSync(resolve(trackRoot, "data/registry.json"), "utf8")) as {
	entries: RegistryEntry[]
}
const tunable = registry.entries.filter((entry) => entry.tunable)

/** site index -> entry, and a per-file lookup keyed by the literal's exact source offset. */
const siteIndexByFileStart = new Map<string, number>()
tunable.forEach((entry, index) => {
	siteIndexByFileStart.set(`${entry.file}@${entry.start}`, index)
})

const COMPARISONS = new Map<ts.SyntaxKind, string>([
	[ts.SyntaxKind.LessThanToken, "<"],
	[ts.SyntaxKind.GreaterThanToken, ">"],
	[ts.SyntaxKind.LessThanEqualsToken, "<="],
	[ts.SyntaxKind.GreaterThanEqualsToken, ">="],
	[ts.SyntaxKind.EqualsEqualsEqualsToken, "==="],
	[ts.SyntaxKind.ExclamationEqualsEqualsToken, "!=="],
])

rmSync(variantDir, { recursive: true, force: true })
mkdirSync(variantDir, { recursive: true })
cpSync(runtimeDir, variantDir, { recursive: true })
rmSync(resolve(variantDir, "test"), { recursive: true, force: true })

const probeModule = `/**
 * Track P instrumentation runtime (generated by probe/instrument.ts — do not edit by hand).
 *
 * Lives inside the copied tree so the mirror keeps the closed-import invariant of the original.
 */
const SITE_COUNT = ${tunable.length}

export const evaluations = new Float64Array(SITE_COUNT)
/** Reads of a named constant or policy field. A declaration is evaluated once; its uses are what fire. */
export const reads = new Float64Array(SITE_COUNT)
export const comparisons = new Float64Array(SITE_COUNT)
/** Flip counters, indexed [site * 6 + k] for k = up/down x 10/20/50 %. */
export const flips = new Float64Array(SITE_COUNT * 6)
/** Closest relative approach of the compared value to the threshold, per site. */
export const nearest = new Float64Array(SITE_COUNT).fill(Number.POSITIVE_INFINITY)

const targetRaw = process.env.TRACK_P_SITE
const target = targetRaw === undefined || targetRaw === "" ? -1 : Number(targetRaw)
const factor = process.env.TRACK_P_FACTOR === undefined ? 1 : Number(process.env.TRACK_P_FACTOR)
/** Absolute override wins over the multiplicative factor when present (used for 0/1 policy switches). */
const absoluteRaw = process.env.TRACK_P_ABSOLUTE
const absolute = absoluteRaw === undefined || absoluteRaw === "" ? null : Number(absoluteRaw)
const census = process.env.TRACK_P_CENSUS === "1"

const RATIOS = [1.1, 0.9, 1.2, 0.8, 1.5, 0.5]

function holds(left: number, right: number, op: number): boolean {
	switch (op) {
		case 0: return left < right
		case 1: return left > right
		case 2: return left <= right
		case 3: return left >= right
		case 4: return left === right
		default: return left !== right
	}
}

export const __P = {
	/**
	 * A tunable literal evaluation. Returns the perturbed value when this site is the target.
	 *
	 * Counting happens only in census mode: these calls sit inside per-pixel loops, and incrementing
	 * on every one of the ~4.6e8 evaluations the census recorded costs roughly 3x runtime. A
	 * perturbation run needs no counters, so it pays baseline speed.
	 */
	v(site: number, value: number): number {
		if (census) evaluations[site] += 1
		if (site !== target) return value
		return absolute === null ? value * factor : absolute
	},
	/**
	 * A read of a named constant or policy field. The declaration is evaluated once at module load,
	 * so \`v\` cannot measure how often such a constant is actually consulted; this can.
	 */
	r(site: number, value: number): number {
		if (census) reads[site] += 1
		return value
	},
	/**
	 * A comparison with a tunable literal operand. \`side\` is 0 when the literal is on the left.
	 * Only the census pass does the flip arithmetic; perturbation runs skip it.
	 */
	cmp(site: number, left: number, right: number, op: number, side: number): boolean {
		const result = holds(left, right, op)
		if (!census) return result
		comparisons[site] += 1
		const threshold = side === 0 ? left : right
		const other = side === 0 ? right : left
		if (threshold !== 0 && Number.isFinite(threshold) && Number.isFinite(other)) {
			const approach = Math.abs(other - threshold) / Math.abs(threshold)
			if (approach < nearest[site]!) nearest[site] = approach
		}
		for (let index = 0; index < 6; index += 1) {
			const moved = threshold * RATIOS[index]!
			const perturbed = side === 0 ? holds(moved, right, op) : holds(left, moved, op)
			if (perturbed !== result) flips[site * 6 + index] += 1
		}
		return result
	},
}
`
mkdirSync(resolve(variantDir, "src/internal"), { recursive: true })
writeFileSync(resolve(variantDir, "src/internal/__track-p.ts"), probeModule)

/**
 * Most thresholds are named constants or policy fields consulted from other modules. Their
 * declaration is evaluated once at module load, so counting evaluations there would report every
 * such constant as firing exactly once — indistinguishable from dead. These two maps let the
 * transform instrument the *reads* instead: `MINIMUM_DOMAIN_POPULATION` wherever it is referenced,
 * and `ALBUM_ARTWORK_PALETTE_V2_POLICY.mark.minimumFill` wherever that path is accessed.
 */
const namedConstSites = new Map<string, number>()
const policyFieldSites = new Map<string, number>()
tunable.forEach((entry, index) => {
	if (entry.propertyKey === null) {
		// A module-level `const NAME = <literal>`: the enclosing declaration is the constant itself.
		if (entry.enclosing === entry.topLevel && /^[A-Za-z_$][\w$]*$/u.test(entry.enclosing)) {
			if (!namedConstSites.has(entry.enclosing)) namedConstSites.set(entry.enclosing, index)
		}
	} else {
		policyFieldSites.set(`${entry.topLevel}.${entry.propertyKey}`, index)
	}
})

/** Dotted text of a property-access chain, or null when it is not a plain chain. */
function dottedText(node: ts.Node): string | null {
	if (ts.isIdentifier(node)) return node.text
	if (ts.isPropertyAccessExpression(node)) {
		const base = dottedText(node.expression)
		return base === null ? null : `${base}.${node.name.text}`
	}
	return null
}

const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed, removeComments: false })
let wrappedLiterals = 0
let wrappedComparisons = 0
let wrappedReads = 0

const byFile = new Map<string, RegistryEntry[]>()
for (const entry of tunable) {
	const list = byFile.get(entry.file) ?? []
	list.push(entry)
	byFile.set(entry.file, list)
}

for (const [file, entries] of byFile) {
	const name = file.replace(/^.*\//u, "")
	const path = resolve(runtimeDir, "src/internal", name)
	const text = readFileSync(path, "utf8")
	const source = ts.createSourceFile(path, text, ts.ScriptTarget.ESNext, true, ts.ScriptKind.TS)

	const siteOf = (node: ts.Node): number | undefined =>
		siteIndexByFileStart.get(`${file}@${node.getStart(source)}`)

	/**
	 * True when this identifier / property name occupies a *declaring* or *naming* position rather
	 * than being a value read. Instrumenting those produces syntactically invalid code.
	 */
	const isNamingPosition = (node: ts.Node): boolean => {
		const parent = node.parent
		if (!parent) return true
		// Anything inside a type is contract, not a value read. `quadrantCoverage` is both a runtime
		// constant and a type-member name; wrapping the latter emits a call in a type position.
		for (let ancestor: ts.Node | undefined = parent; ancestor; ancestor = ancestor.parent) {
			if (ts.isTypeNode(ancestor) || ts.isTypeAliasDeclaration(ancestor)
				|| ts.isInterfaceDeclaration(ancestor) || ts.isPropertySignature(ancestor)
				|| ts.isMethodSignature(ancestor) || ts.isTypeParameterDeclaration(ancestor)) return true
			if (ts.isSourceFile(ancestor)) break
		}
		if (ts.isPropertySignature(parent) && parent.name === node) return true
		// `{ quadrantCoverage }` — handled by expanding the shorthand, not by wrapping in place.
		if (ts.isShorthandPropertyAssignment(parent)) return true
		if (ts.isVariableDeclaration(parent) && parent.name === node) return true
		if (ts.isPropertyAssignment(parent) && parent.name === node) return true
		if (ts.isPropertyAccessExpression(parent) && parent.name === node) return true
		if (ts.isBindingElement(parent) || ts.isParameter(parent)) return true
		if (ts.isImportSpecifier(parent) || ts.isExportSpecifier(parent)) return true
		if (ts.isImportClause(parent) || ts.isNamespaceImport(parent)) return true
		if (ts.isFunctionDeclaration(parent) || ts.isMethodDeclaration(parent)) return true
		if (ts.isTypeReferenceNode(parent) || ts.isQualifiedName(parent)) return true
		if (ts.isEnumMember(parent) || ts.isTypeAliasDeclaration(parent)) return true
		return false
	}

	/** The registry site a comparison operand refers to, whether literal, named const, or policy field. */
	const operandSite = (node: ts.Expression): number | undefined => {
		if (ts.isNumericLiteral(node)) return siteOf(node)
		if (ts.isIdentifier(node)) return namedConstSites.get(node.text)
		if (ts.isPropertyAccessExpression(node)) {
			const dotted = dottedText(node)
			return dotted === null ? undefined : policyFieldSites.get(dotted)
		}
		return undefined
	}

	const transformer: ts.TransformerFactory<ts.SourceFile> = (context) => (root) => {
		const readWrap = (site: number, expression: ts.Expression): ts.Expression => {
			wrappedReads += 1
			return context.factory.createCallExpression(
				context.factory.createPropertyAccessExpression(
					context.factory.createIdentifier("__P"), "r"),
				undefined,
				[context.factory.createNumericLiteral(site), expression],
			)
		}
		const visit = (node: ts.Node): ts.Node => {
			if (ts.isBinaryExpression(node) && COMPARISONS.has(node.operatorToken.kind)) {
				const leftSite = operandSite(node.left)
				const rightSite = operandSite(node.right)
				const site = leftSite ?? rightSite
				if (site !== undefined) {
					const side = leftSite !== undefined ? 0 : 1
					const opIndex = [...COMPARISONS.keys()].indexOf(node.operatorToken.kind)
					const left = ts.visitNode(node.left, visit) as ts.Expression
					const right = ts.visitNode(node.right, visit) as ts.Expression
					wrappedComparisons += 1
					return context.factory.createCallExpression(
						context.factory.createPropertyAccessExpression(
							context.factory.createIdentifier("__P"), "cmp"),
						undefined,
						[
							context.factory.createNumericLiteral(site),
							left,
							right,
							context.factory.createNumericLiteral(opIndex),
							context.factory.createNumericLiteral(side),
						],
					)
				}
			}
			if (ts.isNumericLiteral(node)) {
				const site = siteOf(node)
				if (site !== undefined) {
					wrappedLiterals += 1
					return context.factory.createCallExpression(
						context.factory.createPropertyAccessExpression(
							context.factory.createIdentifier("__P"), "v"),
						undefined,
						[context.factory.createNumericLiteral(site), context.factory.createNumericLiteral(node.text)],
					)
				}
			}
			// `{ FOO }` must become `{ FOO: __P.r(i, FOO) }`; wrapping the shorthand in place is invalid.
			if (ts.isShorthandPropertyAssignment(node)) {
				const site = namedConstSites.get(node.name.text)
				if (site !== undefined) {
					return context.factory.createPropertyAssignment(
						context.factory.createIdentifier(node.name.text),
						readWrap(site, context.factory.createIdentifier(node.name.text)),
					)
				}
			}
			// Reads of a named constant or a policy field: what actually fires at runtime.
			if (ts.isPropertyAccessExpression(node) && !isNamingPosition(node)) {
				const dotted = dottedText(node)
				const site = dotted === null ? undefined : policyFieldSites.get(dotted)
				if (site !== undefined) return readWrap(site, node)
			}
			if (ts.isIdentifier(node) && !isNamingPosition(node)) {
				const site = namedConstSites.get(node.text)
				if (site !== undefined) return readWrap(site, node)
			}
			return ts.visitEachChild(node, visit, context)
		}
		return ts.visitNode(root, visit) as ts.SourceFile
	}

	const result = ts.transform(source, [transformer])
	const printed = printer.printFile(result.transformed[0] as ts.SourceFile)
	result.dispose()
	writeFileSync(
		resolve(variantDir, "src/internal", name),
		`import { __P } from "./__track-p.ts"\n${printed}`,
	)
	process.stdout.write(`  instrumented ${name} (${entries.length} sites)\n`)
}

writeFileSync(
	resolve(trackRoot, "data/sites.json"),
	`${JSON.stringify({
		schemaVersion: 1,
		count: tunable.length,
		sites: tunable.map((entry, index) => ({
			index,
			id: entry.id,
			file: entry.file,
			line: entry.line,
			value: entry.value,
			propertyKey: entry.propertyKey,
			topLevel: entry.topLevel,
			enclosing: entry.enclosing,
			lineText: entry.lineText,
			docComment: entry.docComment,
			/** True when firing is measured at read sites rather than at the declaration. */
			readInstrumented: entry.propertyKey === null
				? namedConstSites.get(entry.enclosing) === index
				: policyFieldSites.get(`${entry.topLevel}.${entry.propertyKey}`) === index,
		})),
	}, null, "\t")}\n`,
)

process.stdout.write(`variant at ${variantDir}\n`)
process.stdout.write(`${tunable.length} sites; ${wrappedLiterals} literal wraps, `
	+ `${wrappedComparisons} comparison wraps, ${wrappedReads} read wraps\n`)
process.stdout.write(`${namedConstSites.size} named constants, ${policyFieldSites.size} policy fields tracked by read\n`)
