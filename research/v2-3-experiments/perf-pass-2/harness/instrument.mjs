import { cpSync, mkdirSync, readFileSync, rmSync, symlinkSync, writeFileSync } from "node:fs"
import { resolve, dirname } from "node:path"
import { fileURLToPath } from "node:url"

/**
 * Builds an INSTRUMENTED COPY of `research/v2-3` under a scratch root.
 *
 * Why a copy: the pass-1 arm established that `node --cpu-prof` misattributes in this codebase by
 * more than 4x (it reported `buildRegionGraph` at 51.4% self where direct bracketing said 12.3%,
 * and never surfaced the real leader at all). The only trustworthy signal here is
 * `process.cpuUsage()` bracketed around the exact call — but that requires editing the source, and
 * the source must stay pristine so the byte-identity gate keeps measuring the real tree. So the
 * instrumentation is applied to a throwaway copy.
 *
 * The transform is deliberately dumb and syntactic: `function NAME(` becomes
 * `function NAME__profInner(`, and a hoisted wrapper of the original name is appended. Function
 * declarations hoist, so appending is safe regardless of where the original sat in the file.
 *
 * Nesting is handled by a stack that subtracts each callee's inclusive time from its caller, so the
 * report carries BOTH inclusive and self time. Instrumenting a function called ~100k times would be
 * dominated by the two `cpuUsage()` syscalls per invocation, so only coarse-grained functions
 * (call counts in the tens to low thousands) belong in TARGETS.
 */

