function insertPhases(path, phases) {
	const lines = readFileSync(path, "utf8").split("\n")
	for (const [anchor, name] of phases) {
		const index = lines.findIndex((line) => line.startsWith(anchor))
		if (index === -1) throw new Error(`instrument: phase anchor not found in ${path}: ${anchor}`)
		lines[index] = `__profPhase(${JSON.stringify(name)});\n${lines[index]}`
	}
	writeFileSync(path, lines.join("\n"))
}

function instrumentFile(path, names) {
	let text = readFileSync(path, "utf8")
	const appended = []
	for (const name of names) {
		const pattern = new RegExp(`^(export )?function ${name}\\(`, "m")
		const match = pattern.exec(text)
		if (!match) throw new Error(`instrument: ${name} not found in ${path}`)
		const exported = Boolean(match[1])
		text = text.replace(pattern, `function ${name}__profInner(`)
		appended.push(
			`${exported ? "export " : ""}function ${name}(...args) {\n` +
			`\tconst frame = __profEnter("${name}")\n` +
			`\ttry { return ${name}__profInner(...args) } finally { __profExit(frame) }\n` +
			`}`,
		)
	}
	const relative = "./__prof.ts"
	text = `import { __profEnter, __profExit, __profPhase } from "${relative}"\n${text}\n\n${appended.join("\n")}\n`
	writeFileSync(path, text)
}

export function buildInstrumentedTree(outRoot) {
	rmSync(outRoot, { recursive: true, force: true })
	mkdirSync(resolve(outRoot, "research"), { recursive: true })
	cpSync(resolve(repoRoot, "research/v2-3"), resolve(outRoot, "research/v2-3"), { recursive: true })
	cpSync(resolve(repoRoot, "research/v2-3-experiments/perf-pass-2"),
		resolve(outRoot, "research/v2-3-experiments/perf-pass-2"), { recursive: true })
	cpSync(resolve(repoRoot, "research/v2-3-experiments/perf-pass"),
		resolve(outRoot, "research/v2-3-experiments/perf-pass"), { recursive: true })
	// The copy lives outside the repo, so package resolution needs a way back to `sharp`/`apca-w3`.
	symlinkSync(resolve(repoRoot, "node_modules"), resolve(outRoot, "node_modules"))
	writeFileSync(resolve(outRoot, "research/v2-3/src/internal/__prof.ts"), PROF_MODULE)
	const byFile = new Map()
	for (const [file, name] of TARGETS) {
		if (!byFile.has(file)) byFile.set(file, [])
		byFile.get(file).push(name)
	}
	const phasesByFile = new Map()
	for (const [file, anchor, name] of PHASES) {
		if (!phasesByFile.has(file)) phasesByFile.set(file, [])
		phasesByFile.get(file).push([anchor, name])
	}
	// Phases go in first: they match on original source prefixes, which the wrapper rewrite would
	// otherwise have already renamed.
	for (const [file, phases] of phasesByFile) {
		insertPhases(resolve(outRoot, "research/v2-3/src/internal", file), phases)
	}
	for (const [file, names] of byFile) {
		instrumentFile(resolve(outRoot, "research/v2-3/src/internal", file), names)
	}
	return outRoot
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const out = resolve(process.argv[2] ?? "")
	if (!process.argv[2]) throw new Error("usage: instrument.mjs <out-root>")
	buildInstrumentedTree(out)
	process.stderr.write(`instrumented tree at ${out}\n`)
}
