const PROF_MODULE = `/** Generated by perf-pass-2 instrument.mjs. Not part of the algorithm. */
const stack = []
export const totals = new Map()

function micros() {
	const usage = process.cpuUsage()
	return usage.user + usage.system
}

/**
 * Flat phase marks, for splitting one long function into its stages.
 *
 * Independent of the call stack: a mark closes whatever phase was open and opens the named one.
 * \`__profExit\` closes any open phase, so time after a marked function returns is never charged to
 * its last stage.
 */
let phaseName = null
let phaseStart = 0

export function __profPhase(name) {
	if (phaseName !== null) {
		let row = totals.get(phaseName)
		if (!row) totals.set(phaseName, (row = { inclusive: 0, self: 0, calls: 0 }))
		const elapsed = micros() - phaseStart
		row.inclusive += elapsed
		row.self += elapsed
		row.calls += 1
	}
	phaseName = name
	phaseStart = micros()
}

export function __profEnter(name) {
	const frame = { name, start: micros(), childTotal: 0 }
	stack.push(frame)
	return frame
}

export function __profExit(frame) {
	if (phaseName !== null) __profPhase(null)
	stack.pop()
	const inclusive = micros() - frame.start
	const parent = stack[stack.length - 1]
	if (parent) parent.childTotal += inclusive
	let row = totals.get(frame.name)
	if (!row) totals.set(frame.name, (row = { inclusive: 0, self: 0, calls: 0 }))
	row.inclusive += inclusive
	row.self += inclusive - frame.childTotal
	row.calls += 1
}

export function __profReset() {
	stack.length = 0
	phaseName = null
	totals.clear()
}

export function __profSnapshot() {
	return [...totals.entries()].map(([name, row]) => ({ name, ...row }))
}
`

/**
 * Flat stage marks inside functions too long to read as one number. `[file, anchor, name]`: a
 * `__profPhase("name")` is inserted immediately BEFORE the first line whose text starts with
 * `anchor`, so the stage that follows is attributed to `name`. Anchors are exact source prefixes and
 * the build throws if one stops matching, so a refactor cannot silently produce a wrong profile.
 */
